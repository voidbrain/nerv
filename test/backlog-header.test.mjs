import { test } from 'node:test';
import assert from 'node:assert/strict';
import { headerProblems, HEADER_CHARS } from '../tools/backlog-recap.mjs';

const START = '<!-- recap:start · generated by tools/backlog-recap.mjs from the records; do not edit by hand -->';
const doc = (...head) => ['# Backlog', '', ...head, '', START, '…', '<!-- recap:end -->', '', '## Bugs', ''].join('\n');

test('a two-line header passes', () => {
  assert.deepEqual(
    headerProblems(
      doc('Current work ledger, reviewed against main `abc1234`. PR #1 reconciled.', '[Rules](BACKLOG-RULES.md)'),
    ),
    [],
  );
});
test('a third header line fails', () => {
  assert.match(headerProblems(doc('a', 'b', 'c'))[0], /3 lines; keep at most 2/);
});
test('a long reconciliation line fails and names the archive log', () => {
  const p = headerProblems(doc('x'.repeat(HEADER_CHARS + 1), 'links'));
  assert.equal(p.length, 1);
  assert.match(p[0], /reconciliation-<year>\.md/);
});
test('without a recap the header ends at the first section', () => {
  assert.deepEqual(headerProblems(['# Backlog', '', 'one', 'two', '', '## Bugs', 'x', 'y', 'z'].join('\n')), []);
});
