#!/usr/bin/env node
// Milestone status in docs/ROADMAP.md, derived from the backlog records so the roadmap never carries a status of its own.
// The milestone table's Records column is the placement: every feature that is not closed sits in exactly one milestone.
//
//   node tools/roadmap-status.mjs           rewrite the generated status block
//   node tools/roadmap-status.mjs --check   fail on an unknown ID, an open feature placed nowhere or twice, or a stale block
import {readFileSync,writeFileSync,readdirSync,existsSync} from 'node:fs';
import {join} from 'node:path';
import {parseRecords} from './backlog-recap.mjs';

const ROOT=process.cwd();const ROADMAP=join(ROOT,'docs/ROADMAP.md');const BACKLOG=join(ROOT,'docs/BACKLOG.md');const ARCHIVE=join(ROOT,'docs/archive');
export const START='<!-- roadmap-status:start · generated by tools/roadmap-status.mjs from the backlog records; do not edit by hand -->';
export const END='<!-- roadmap-status:end -->';
const ID=/\b[FB]-\d{3,}\b/g;

/** Milestone rows of the first table whose header has a Records column: name and the IDs in that column. */
export function milestones(text){
 const lines=text.split('\n');const at=lines.findIndex(l=>/^\|\s*Milestone\s*\|/.test(l)&&/\|\s*Records\s*\|/.test(l));
 if(at<0)return null;
 const cols=lines[at].split('|').map(c=>c.trim());const rec=cols.indexOf('Records');const out=[];
 for(let i=at+2;i<lines.length&&lines[i].startsWith('|');i++){
  const cells=lines[i].split('|').map(c=>c.trim());
  out.push({name:cells[1],ids:[...(cells[rec]??'').matchAll(ID)].map(m=>m[0])});
 }
 return out;
}
/** Latest known status per ID: the active ledger wins over an archived copy. */
export function statuses(active,archived){
 const s=new Map();for(const r of archived)s.set(r.id,'Closed');for(const r of active)s.set(r.id,r.status);return s;
}
const DONE=new Set(['Implemented','Verified']);
/** One milestone's state from its records: Delivered, Awaiting verification, In progress or Planned. */
export function state(list){
 if(!list.length)return 'Planned';
 if(list.every(s=>s==='Closed'))return 'Delivered';
 if(list.every(s=>s==='Closed'||DONE.has(s)))return 'Awaiting verification';
 return list.some(s=>s==='Closed'||DONE.has(s))?'In progress':'Planned';
}
export function block(rows,status){
 const out=[START,'| Milestone | Status | Closed | Implemented / verified | Open | Still open |','|---|---|---:|---:|---:|---|'];
 for(const m of rows){
  const st=m.ids.map(id=>status.get(id));
  const open=m.ids.filter(id=>{const s=status.get(id);return s!=='Closed'&&!DONE.has(s);});
  out.push(`| ${m.name} | ${state(st)} | ${st.filter(s=>s==='Closed').length} | ${st.filter(s=>DONE.has(s)).length} | ${open.length} | ${open.join(', ')||'—'} |`);
 }
 return [...out,END].join('\n');
}
/** Problems that make the roadmap disagree with the backlog. */
export function problems(text,active,archived){
 const rows=milestones(text);if(!rows)return ['docs/ROADMAP.md has no milestone table with a Records column.'];
 const status=statuses(active,archived);const out=[];
 const outside=text.replace(new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')}[\\s\\S]*?${END}`),'');
 for(const id of new Set(outside.match(ID)??[]))if(!status.has(id))out.push(`${id} is cited in the roadmap but is not a backlog record.`);
 const placed=new Map();
 for(const m of rows)for(const id of m.ids){if(id.startsWith('B-'))out.push(`${id} in ${m.name}: milestones hold features (F-), not bugs.`);placed.set(id,[...(placed.get(id)??[]),m.name]);}
 for(const [id,where] of placed)if(where.length>1)out.push(`${id} is placed in more than one milestone: ${where.join('; ')}.`);
 for(const r of active)if(r.kind==='feature'&&r.status!=='Closed'&&!placed.has(r.id))out.push(`${r.id} (${r.status}) is not placed in any milestone: add it to a Records cell.`);
 const want=block(rows,status);const a=text.indexOf(START),b=text.indexOf(END);
 if(a<0||b<0)out.push('The generated status block is missing: run npm run roadmap:status.');
 else if(text.slice(a,b+END.length)!==want)out.push('The milestone status block does not match the backlog: run npm run roadmap:status.');
 return out;
}
export function place(text,want){
 const a=text.indexOf(START);
 if(a>=0)return text.slice(0,a)+want+text.slice(text.indexOf(END,a)+END.length);
 const first=text.indexOf('\n## ');return first<0?text+'\n'+want+'\n':text.slice(0,first)+'\n\n'+want+'\n'+text.slice(first);
}
function records(){
 const active=parseRecords(readFileSync(BACKLOG,'utf8'));
 const archived=existsSync(ARCHIVE)?readdirSync(ARCHIVE).filter(f=>/^backlog-\d{4}\.md$/.test(f)).flatMap(f=>parseRecords(readFileSync(join(ARCHIVE,f),'utf8'),true)):[];
 return {active,archived};
}
if(import.meta.url===`file://${process.argv[1]}`){
 const {active,archived}=records();const text=readFileSync(ROADMAP,'utf8');
 if(process.argv.includes('--check')){
  const p=problems(text,active,archived);
  if(p.length){for(const x of p)console.error(x);process.exit(1);}
  console.log(`Roadmap matches the backlog: ${milestones(text).length} milestones, every open feature placed once.`);
 }else{
  const rows=milestones(text);if(!rows){console.error('docs/ROADMAP.md has no milestone table with a Records column.');process.exit(1);}
  writeFileSync(ROADMAP,place(text,block(rows,statuses(active,archived))));console.log('Roadmap status written.');
 }
}
